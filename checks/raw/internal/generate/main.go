package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strconv"
)

type spdxLicense struct {
	LicenseID     string `json:"licenseId"`
	Name          string `json:"name"`
	IsOsiApproved bool   `json:"isOsiApproved"`
	IsFsfLibre    bool   `json:"isFsfLibre"`
}

type spdxList struct {
	LicenseListVersion string        `json:"licenseListVersion"`
	Licenses           []spdxLicense `json:"licenses"`
}

func main() {
	inputPath := flag.String("input", "checks/raw/internal/licenses/licenses.json", "path to pinned SPDX licenses.json")
	outputPath := flag.String("output", "checks/raw/license_map.go", "output path for generated Go license map")
	flag.Parse()

	data, err := os.ReadFile(*inputPath)
	if err != nil {
		log.Fatalf("failed to read input file %s: %v", *inputPath, err)
	}

	var list spdxList
	if err := json.Unmarshal(data, &list); err != nil {
		log.Fatalf("failed to parse SPDX json: %v", err)
	}

	approved := make(map[string]string)
	for _, lic := range list.Licenses {
		if lic.IsOsiApproved || lic.IsFsfLibre {
			approved[lic.LicenseID] = lic.Name
		}
	}

	keys := make([]string, 0, len(approved))
	for k := range approved {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var buf bytes.Buffer
	buf.WriteString(`// Copyright 2024 OpenSSF Scorecard Authors
//
// Licensed under the Apache License, Version 2.0 (the "License");
// you may not use this file except in compliance with the License.
// You may obtain a copy of the License at
//
//      http://www.apache.org/licenses/LICENSE-2.0
//
// Unless required by applicable law or agreed to in writing, software
// distributed under the License is distributed on an "AS IS" BASIS,
// WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
// See the License for the specific language governing permissions and
// limitations under the License.

`)
	fmt.Fprintf(&buf, "// Code generated by checks/raw/internal/generate/main.go. DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "// SPDX-License-List-Version: %s\n\n", list.LicenseListVersion)
	buf.WriteString("package raw\n\n")
	buf.WriteString("var fsfOsiApprovedLicenseMap = map[string]fsfOsiLicenseType{\n")

	for _, k := range keys {
		escapedKey := strconv.Quote(k)
		escapedName := strconv.Quote(approved[k])
		fmt.Fprintf(&buf, "\t%s: {Name: %s},\n", escapedKey, escapedName)
	}
	buf.WriteString("}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("failed to format generated code: %v\nCode:\n%s", err, buf.String())
	}

	if err := os.WriteFile(*outputPath, formatted, 0o600); err != nil {
		log.Fatalf("failed to write output file %s: %v", *outputPath, err)
	}

	log.Printf("Successfully generated %s with %d approved licenses from SPDX %s\n", *outputPath, len(keys), list.LicenseListVersion)
}
